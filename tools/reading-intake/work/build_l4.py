NUM_RE = re.compile(r"^\s*[0-9]{1,2}(?=[^\d])")
PINYIN_RE = re.compile(r"\s*\([a-zA-Zāáǎàēéěèīíǐìōóǒòūúǔùǖǘǚǜü]+\)")
NOTE_RE = re.compile(r"\s*[（(](?:有删改|选文有改动|根据相关材料编写|本文作者[^）)]*)[）)]")
SPACE_RE = re.compile(r"\s+")
ALLOWED_LEADING = ("月", "年", "日", "时", "分", "秒", "件", "个", "天", "次", "万", "千", "百", "多", "点")


def clean_numbered(lines):
    out = []
    for line in lines:
        stripped = line.strip()
        if NUM_RE.match(stripped):
            tail = stripped.lstrip("0123456789")
            # 行首数字是内容的一部分（如“1月20日”“405年”）时保留
            if not tail.startswith(ALLOWED_LEADING):
                stripped = NUM_RE.sub("", stripped)
        if stripped:
            out.append(stripped)
    return out


def polish(text):
    text = PINYIN_RE.sub("", text)
    text = NOTE_RE.sub("", text)
    text = re.sub(r"\s+", "", text)
    return text


def han_count(text):
    return len(re.findall(r"[\u4e00-\u9fff]", text))


