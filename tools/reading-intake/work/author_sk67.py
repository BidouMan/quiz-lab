def build(rec):
    rid = rec["id"]
    src = rec["sourceId"]
    label = SRC_LABEL[src.split("-")[0]] if src.startswith("ns21") else SRC_LABEL["szx"]
    locator = f"ns21cnjy batch 素材 {src}" if src.startswith("ns21") else f"szxuexiao passages 素材 {src}"
    tag = rec["tag"]
    review = (
        f"2026-11-08 {tag} 专项自命题。素材：{label}《{rec['title']}》，"
        f"已删卷面题号、答案残片与网页标记，正文{rec['charCount']}字。"
        f"原卷虽有题，但缺少明确的“结构/写法”或“非连续性文本”考查，四题全部新命："
        + ("一题标“非连续性文本”，要求跨材料整合；" if tag == "SK7" else "一题标“写法结构”，要求辨识结构或写法；")
        + "客观2题、主观1题，考点覆盖4类。难度按脚本口径：含"
        + ("非连续性文本" if tag == "SK7" else "写法结构")
        + "，一律记为难。人工复核：" + HUMAN[rid]
    )
    draft = {
        "id": rid,
        "sourceSeq": src,
        "kind": "extracurricular",
        "scope": "extracurricular",
        "term": "3A",
        "sourceId": src,
        "title": rec["title"],
        "theme": rec["theme"],
        "status": "verified",
        "sourceCharCount": rec["charCount"],
        "charCount": rec["charCount"],
        "paragraphs": rec["paragraphs"],
        "sources": [{"label": f"{label}《{rec['title']}》", "locator": locator}],
        "review": review,
        "questions": QUESTIONS[rid],
    }
    return draft


def main():
    for line in open(CANDS, encoding="utf-8"):
        if not line.strip():
            continue
        rec = json.loads(line)
        draft = build(rec)
        path = os.path.join(OUT, f"{draft['id']}.json")
        with open(path, "w", encoding="utf-8") as f:
            json.dump(draft, f, ensure_ascii=False, indent=2)
            f.write("\n")
        print("写入", draft["id"], draft["title"], draft["charCount"], "字")


if __name__ == "__main__":
    main()
