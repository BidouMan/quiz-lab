HAN = re.compile(r"[\u4e00-\u9fff]")


def han(s):
    return len(HAN.findall(s))


def qc(stem, options, answer, explain, skill, origin):
    return {"type": "choice", "stem": stem, "options": options, "answer": answer,
            "explain": explain, "score": 2, "skill": skill, "answerSource": "new", "origin": origin}


def qf(stem, blanks, explain, skill, origin):
    return {"type": "fill", "stem": stem, "blanks": blanks, "explain": explain,
            "score": 2, "skill": skill, "answerSource": "new", "origin": origin}


def qs(stem, scoring, answer, skill, origin):
    return {"type": "short", "stem": stem, "scoring": scoring, "answer": answer,
            "score": 4, "skill": skill, "answerSource": "new", "origin": origin}


def org(action, original, note):
    return {"action": action, "original": original, "note": note}


